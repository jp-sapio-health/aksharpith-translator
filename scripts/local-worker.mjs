// ── PDF extraction for large files ───────────────────────────────────────────

async function pollForExtractions() {
  if (processing) return;

  try {
    const snapshot = await db.collection('extractions')
      .where('status', '==', 'pending')
      .limit(1)
      .get();

    if (snapshot.empty) return;

    processing = true;
    const doc = snapshot.docs[0];
    const extractionId = doc.id;
    const data = doc.data();

    console.log(`\n[worker] Extracting PDF: ${data.filename} (${data.pages} pages, ${(data.fileSizeBytes / 1024 / 1024).toFixed(1)} MB)`);

    try {
      await db.collection('extractions').doc(extractionId).set({
        status: 'running',
        progress: 'Splitting PDF into page chunks...',
      }, { merge: true });

      const { readFileSync } = await import('node:fs');
      const buf = data.filePath ? readFileSync(data.filePath) : Buffer.from(data.fileBase64 || '', 'base64');
      const pages = data.pages || 1;

      // Split into chunks of ~20 pages
      const { PDFDocument } = await import('pdf-lib');
      const srcDoc = await PDFDocument.load(buf);
      const totalPages = srcDoc.getPageCount();
      const pagesPerChunk = Math.min(20, totalPages);
      const chunks = [];

      for (let start = 0; start < totalPages; start += pagesPerChunk) {
        const end = Math.min(start + pagesPerChunk, totalPages);
        const newDoc = await PDFDocument.create();
        const copiedPages = await newDoc.copyPages(srcDoc, Array.from({ length: end - start }, (_, i) => start + i));
        for (const p of copiedPages) newDoc.addPage(p);
        const bytes = await newDoc.save();
        chunks.push(Buffer.from(bytes));
      }

      console.log(`  Split into ${chunks.length} chunks of ~${pagesPerChunk} pages`);

      // Extract text from each chunk via Claude
      const PDF_PROMPT = `Extract ALL text from this PDF document exactly as written. Preserve:
- Every paragraph (blank line between paragraphs)
- All Gujarati Unicode text exactly as it appears
- All numbers, dates, names, verses
- Chapter/section headings (mark as "=== CHAPTER: <title> ===" on its own line)
- Verse/kirtan lines on separate lines
Return ONLY the extracted text — no commentary, no notes, no preamble.`;

      const parts = [];
      for (let i = 0; i < chunks.length; i++) {
        await db.collection('extractions').doc(extractionId).set({
          progress: `Extracting text from pages ${i * pagesPerChunk + 1}–${Math.min((i + 1) * pagesPerChunk, totalPages)} of ${totalPages}...`,
        }, { merge: true });

        console.log(`  Extracting chunk ${i + 1}/${chunks.length}...`);
        // Write PDF chunk to temp file for claude CLI to read
        const { writeFileSync, unlinkSync } = await import('node:fs');
        const { tmpdir } = await import('node:os');
        const tmpPath = `${tmpdir()}/aksharpith-extract-${i}.pdf`;
        writeFileSync(tmpPath, chunks[i]);
        try {
          const text = await callClaude({
            model: 'claude-haiku-4-5-20251001',
            max_tokens: 16000,
            system: 'You are a document text extractor. Extract all text faithfully.',
            messages: [{ role: 'user', content: `${PDF_PROMPT}\n\nThe PDF file is at: ${tmpPath}\nRead and extract ALL text from it.` }],
          });
          parts.push(text);
        } finally {
          try { unlinkSync(tmpPath); } catch { /* ok */ }
        }
      }

      const fullText = parts.join('\n\n');
      const wordCount = fullText.trim().split(/\s+/).filter(Boolean).length;

      // Detect chapters
      const lines = fullText.split('\n');
      const chapterPattern = /^===\s*CHAPTER:\s*(.+?)\s*===$/i;
      const chapters = [];
      for (let i = 0; i < lines.length; i++) {
        const m = lines[i].trim().match(chapterPattern);
        if (m) chapters.push({ title: m[1], startLine: i });
      }

      await db.collection('extractions').doc(extractionId).set({
        status: 'completed',
        text: fullText,
        wordCount,
        chapters: chapters.length > 1 ? chapters : null,
        progress: `Extracted ${wordCount.toLocaleString()} words from ${totalPages} pages`,
      }, { merge: true });

      // Clean up the source file and Firestore data
      if (data.filePath) {
        try { const { unlinkSync } = await import('node:fs'); unlinkSync(data.filePath); } catch { /* ok */ }
      }
      await db.collection('extractions').doc(extractionId).update({
        fileBase64: '', filePath: '',
      });

      console.log(`[worker] Extraction complete: ${wordCount} words, ${chapters.length} chapters`);
    } catch (err) {
      console.error(`[worker] Extraction failed:`, err.message);
      await db.collection('extractions').doc(extractionId).set({
        status: 'failed',
        error: err.message || 'Extraction failed',
      }, { merge: true });
    } finally {
      processing = false;
    }
  } catch (err) {
    console.error('[worker] Extraction poll error:', err.message);
  }
}

// ── Transliteration-first pipeline (page-by-page OCR) ───────────────────────
//
// New job system. Parent doc lives at `transliterationJobs/{jobId}` with N
// child page docs at `pages/{0001..N}`. This worker:
//   1. Claims one pending page at a time (serial for now; bump to 3-concurrent
//      in a follow-up once we've proven the OAuth path is stable).
//   2. Downloads the source PDF from Vercel Blob (cached per parent jobId so
//      we don't re-fetch for every page in a book).
//   3. Renders just that page to PNG via pdf-to-png-converter.
//   4. Calls the Agent SDK with an image content block to OCR Gujarati text.
//   5. Writes text back to the page doc and bumps parent.pagesCompleted.
//   6. When pagesCompleted === totalPages, transitions parent to assembling →
//      transliterating → done in pollForTransliterationJobs.

import { Buffer as NodeBuffer } from 'node:buffer';
import { randomUUID } from 'node:crypto';
import { writeFileSync, unlinkSync } from 'node:fs';
import { resolve as resolvePath } from 'node:path';
import { FieldValue } from 'firebase-admin/firestore';

const WORKER_ID = `worker-${process.pid}-${randomUUID().slice(0, 6)}`;
const STALE_CLAIM_MS = 10 * 60 * 1000; // 10 min — reaper unclaims pages held this long

// In-memory cache: jobId → Buffer of source PDF. Cleared once the parent
// transitions out of ocr_running. Each entry sized at the original PDF size
// (typically <30 MB) so this is bounded by concurrent jobs (1 for now).
const pdfCache = new Map();

// Lazy-load PROMPT for OCR — kept identical to translate-cli.mjs to match the
// established formatting contract from the Sethji smoke test.
const PAGE_OCR_PROMPT = `Extract ALL text from this image of a single PDF page exactly as written. This is a Gujarati text — preserve:
- All Gujarati Unicode text exactly as it appears
- All English text exactly
- All numbers, dates, names, verses
- Paragraph breaks and structure
- Any headings, bullet points, or numbered lists

Return ONLY the extracted text — no commentary, no notes, no preamble.`;

let transliteratorSystemPrompt = null;
async function getTransliteratorSystem() {
  if (transliteratorSystemPrompt) return transliteratorSystemPrompt;
  const { execSync } = await import('node:child_process');
  const script = `import { buildTransliteratorSystem } from '${ROOT}/lib/rules/transliterator-prompt.ts'; console.log(buildTransliteratorSystem());`;
  transliteratorSystemPrompt = execSync(`npx tsx -e ${JSON.stringify(script)}`, {
    encoding: 'utf-8', cwd: ROOT, maxBuffer: 5 * 1024 * 1024,
    env: { ...process.env, ...env },
  }).trim();
  return transliteratorSystemPrompt;
}

async function callClaudeWithImage(system, prompt, base64Png) {
  // The Agent SDK accepts AsyncIterable<SDKUserMessage> for content arrays.
  const userMessage = {
    type: 'user',
    message: {
      role: 'user',
      content: [
        { type: 'image', source: { type: 'base64', media_type: 'image/png', data: base64Png } },
        { type: 'text', text: prompt },
      ],
    },
    parent_tool_use_id: null,
    session_id: '',
  };
  const promptIter = (async function* () { yield userMessage; })();
  const q = query({
    prompt: promptIter,
    options: {
      systemPrompt: system,
      model: SONNET,
      tools: [],
      maxTurns: 1,
      cwd: SDK_CWD,
      permissionMode: 'bypassPermissions',
    },
  });
  let text = '';
  let errorKind = null;
  for await (const msg of q) {
    if (msg.type === 'assistant') {
      if (msg.error) errorKind = msg.error;
      for (const block of msg.message.content ?? []) {
        if (block.type === 'text' && typeof block.text === 'string') text += block.text;
      }
    } else if (msg.type === 'result' && msg.subtype !== 'success') {
      errorKind = errorKind ?? msg.subtype;
    }
  }
  if (errorKind) throw new Error(`Claude SDK error: ${errorKind}`);
  if (!text.trim()) throw new Error('Empty response from Claude SDK');
  return text;
}

async function getPdfBuffer(jobId, blobUrl) {
  const cached = pdfCache.get(jobId);
  if (cached) return cached;
  const res = await fetch(blobUrl);
  if (!res.ok) throw new Error(`Blob fetch ${res.status} for ${blobUrl}`);
  const buf = NodeBuffer.from(await res.arrayBuffer());
  pdfCache.set(jobId, buf);
  return buf;
}

async function renderPageToPng(pdfBuf, pageNum) {
  // pdfjs-based renderers (incl. pdf-to-png-converter) silently produce blank
  // PNGs for some scanner-output PDFs (Xerox AltaLink, etc.) — pdfjs can't
  // decode their font subsetting and emits a transparent canvas. Sonnet then
  // sees a blank image and OCR returns "I can't see any text" English instead
  // of Gujarati. Shell out to poppler's pdftoppm — much more compatible.
  // Requires `brew install poppler` on the worker host.
  const { execFile } = await import('node:child_process');
  const { promisify } = await import('node:util');
  const { readFileSync: rf } = await import('node:fs');
  const execFileP = promisify(execFile);

  const stamp = `${WORKER_ID}-${pageNum}-${Date.now()}`;
  const tmpPdf = resolvePath(tmpdir(), `aksharpith-${stamp}.pdf`);
  const outRoot = resolvePath(tmpdir(), `aksharpith-${stamp}-out`);
  writeFileSync(tmpPdf, pdfBuf);
  try {
    await execFileP('pdftoppm', [
      '-r', '200',            // ≈ 2x at typical 100 DPI source
      '-png',
      '-f', String(pageNum),
      '-l', String(pageNum),
      '-singlefile',          // emits exactly <outRoot>.png
      tmpPdf,
      outRoot,
    ]);
    const pngPath = `${outRoot}.png`;
    const pngBuf = rf(pngPath);
    try { unlinkSync(pngPath); } catch { /* ok */ }
    return pngBuf;
  } finally {
    try { unlinkSync(tmpPdf); } catch { /* ok */ }
  }
}

async function pollForPageJobs() {
  if (processing) return; // serialise with translation jobs for now
  try {
    // Find active parent jobs first. Avoids collectionGroup queries (which
    // need single-field index exemptions Firebase doesn't auto-create).
    // Fetch parents in pending or ocr_running state, then walk their pages
    // subcollections — those subcollection queries are auto-indexed because
    // their path is fully specified.
    const activeParents = [];
    for (const status of ['pending', 'ocr_running']) {
      const snap = await db.collection('transliterationJobs')
        .where('status', '==', status)
        .limit(5).get();
      activeParents.push(...snap.docs);
    }
    if (activeParents.length === 0) return;

    // Reaper: unclaim pages whose ocr_running claim has gone stale.
    const staleCutoff = new Date(Date.now() - STALE_CLAIM_MS).toISOString();
    for (const parent of activeParents) {
      const stale = await parent.ref.collection('pages')
        .where('status', '==', 'ocr_running')
        .limit(10).get();
      for (const doc of stale.docs) {
        const claimedAt = doc.data().claimedAt;
        if (claimedAt && claimedAt < staleCutoff) {
          await doc.ref.update({ status: 'pending', claimedBy: null, claimedAt: null });
          console.log(`[worker] Reaped stale claim on ${doc.ref.path}`);
        }
      }
    }

    // Pick a pending page across active parents. Order is unimportant —
    // pages are independent OCR units; the UI sorts by pageNum on render.
    // Skipping orderBy() avoids Firebase requiring a composite index on
    // (status, pageNum). Doc ID lexicographic order from the picker matches
    // pageNum order anyway because we pad pageNum with zeros at create time.
    let pageRef = null;
    let parentRef = null;
    for (const parent of activeParents) {
      const snap = await parent.ref.collection('pages')
        .where('status', '==', 'pending')
        .limit(1).get();
      if (!snap.empty) {
        pageRef = snap.docs[0].ref;
        parentRef = parent.ref;
        break;
      }
    }
    if (!pageRef || !parentRef) return;

    processing = true;

    // Claim via transaction. Firestore requires all reads before writes, so
    // we get both docs first, decide what to do, then write.
    const { pageNum, parent } = await db.runTransaction(async (tx) => {
      const [fresh, parentSnap] = await Promise.all([tx.get(pageRef), tx.get(parentRef)]);
      if (!fresh.exists || fresh.data().status !== 'pending') {
        throw new Error('Already claimed');
      }
      if ((fresh.data().attempts ?? 0) >= 3) {
        tx.update(pageRef, { status: 'ocr_failed' });
        throw new Error('Attempts exhausted');
      }
      const now = new Date().toISOString();
      tx.update(pageRef, {
        status: 'ocr_running',
        claimedBy: WORKER_ID,
        claimedAt: now,
        attempts: FieldValue.increment(1),
      });
      // First page claim flips parent from pending → ocr_running.
      if (parentSnap.exists && parentSnap.data().status === 'pending') {
        tx.update(parentRef, { status: 'ocr_running', startedAt: now });
      }
      return { pageNum: fresh.data().pageNum, parent: parentSnap.data() };
    }).catch((err) => {
      if (err.message === 'Already claimed' || err.message === 'Attempts exhausted') return null;
      throw err;
    });

    if (!pageNum) { processing = false; return; }

    console.log(`\n[worker] OCR page ${pageNum}/${parent.totalPages} of ${parent.filename}`);

    try {
      const pdfBuf = await getPdfBuffer(parentRef.id, parent.pdfBlobUrl);
      const pngBuf = await renderPageToPng(pdfBuf, pageNum);
      const text = await callClaudeWithImage(
        'You are an OCR engine. Extract text from images preserving all original formatting and language scripts (especially Gujarati).',
        PAGE_OCR_PROMPT,
        pngBuf.toString('base64'),
      );
      const cleaned = text.replace(/\r\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim();
      const wordCount = cleaned.split(/\s+/).filter(Boolean).length;

      await pageRef.update({
        status: 'ocr_done',
        gujaratiText: cleaned,
        wordCount,
        completedAt: new Date().toISOString(),
        error: null,
      });
      await parentRef.update({ pagesCompleted: FieldValue.increment(1) });
      console.log(`  ✓ page ${pageNum} → ${wordCount} words`);
    } catch (err) {
      console.error(`  ✗ page ${pageNum} failed: ${err.message}`);
      // attempts was already incremented at claim time. Mark failed if cap hit.
      const fresh = await pageRef.get();
      const attempts = fresh.data()?.attempts ?? 3;
      await pageRef.update({
        status: attempts >= 3 ? 'ocr_failed' : 'pending',
        claimedBy: null,
        claimedAt: null,
        error: err.message?.slice(0, 500) ?? 'Unknown OCR error',
      });
      if (attempts >= 3) {
        await parentRef.update({
          status: 'failed',
          error: `Page ${pageNum} OCR failed after 3 attempts: ${err.message?.slice(0, 200)}`,
          completedAt: new Date().toISOString(),
        });
        pdfCache.delete(parentRef.id);
      }
    } finally {
      processing = false;
    }
  } catch (err) {
    console.error('[worker] Page-poll error:', err.message);
    processing = false;
  }
}

async function pollForTransliterationJobs() {
  if (processing) return;
  try {
    // Find a parent whose pages are all done but the transliterator hasn't
    // run yet. Status will be 'ocr_running' (set when first page was claimed).
    const ready = await db.collection('transliterationJobs')
      .where('status', '==', 'ocr_running')
      .limit(5).get();
    if (ready.empty) {
      // Also pick up jobs awaiting optional translation. Single-field query —
      // composite index not required. Filter the secondary condition client-
      // side from the small result set.
      const transReady = await db.collection('transliterationJobs')
        .where('translateRequested', '==', true)
        .limit(20).get();
      const candidate = transReady.docs.find(d => d.data().translationStatus === 'pending');
      if (!candidate) return;
      processing = true;
      try { await processTranslationStage(candidate); } finally { processing = false; }
      return;
    }

    // Find the first parent where pagesCompleted === totalPages.
    const candidate = ready.docs.find(d => {
      const data = d.data();
      return data.pagesCompleted >= data.totalPages;
    });
    if (!candidate) return;

    processing = true;
    try {
      await processTransliterationStage(candidate);
    } finally {
      processing = false;
    }
  } catch (err) {
    console.error('[worker] Transliteration-poll error:', err.message);
    processing = false;
  }
}

async function processTransliterationStage(parentDoc) {
  const parentRef = parentDoc.ref;
  const parent = parentDoc.data();
  console.log(`\n[worker] Transliterating ${parent.filename} (${parent.totalPages} pages)`);

  await parentRef.update({ status: 'assembling' });

  // Read all page docs in pageNum order. We transliterate per page so the UI
  // can render per-page collapsible sections (Sally's UX brief), and so verse
  // boundaries that align with page boundaries stay sensible.
  const pagesSnap = await parentRef.collection('pages').orderBy('pageNum').get();
  const pageDocs = pagesSnap.docs.filter(d => (d.data().gujaratiText ?? '').trim());
  const assembledGujarati = pageDocs
    .map(d => d.data().gujaratiText ?? '')
    .filter(Boolean)
    .join('\n\n');
  await parentRef.update({ gujaratiOutput: assembledGujarati, status: 'transliterating' });

  // Per-page transliteration: each page's gujaratiText becomes that page's
  // transliteratedText on the page doc. Long pages still get chunked
  // internally to stay under Sonnet's context window. Batches of 4 page-
  // jobs run in parallel.
  try {
    const system = await getTransliteratorSystem();
    const PAGE_BATCH = 4;
    let done = 0;

    async function transliteratePage(pageDoc) {
      const pageData = pageDoc.data();
      const guj = pageData.gujaratiText ?? '';
      if (!guj.trim()) return;
      // Skip if already done (resume support).
      if ((pageData.transliteratedText ?? '').trim()) { done++; return; }

      const chunks = deterministicChunk(guj);
      const chunkOuts = [];
      for (const chunk of chunks) {
        const prompt = `Transliterate the following Gujarati passage into Roman script per the rules above. Output ONLY <transliteration>…</transliteration>.\n\nGUJARATI:\n${chunk}`;
        const raw = await callClaude({
          model: SONNET, max_tokens: 8192,
          system,
          messages: [{ role: 'user', content: prompt }],
        });
        const match = raw.match(/<transliteration>([\s\S]*?)<\/transliteration>/);
        if (!match) throw new Error(`page ${pageData.pageNum}: transliterator did not return <transliteration> block`);
        chunkOuts.push(rulesEnforcerAgent(match[1].trim()).text);
      }
      const pageTranslit = chunks.length > 1
        ? rulesEnforcerAgent(assemblerAgent(chunkOuts)).text
        : chunkOuts[0] ?? '';
      await pageDoc.ref.update({ transliteratedText: pageTranslit });
      done++;
      console.log(`    ✓ page ${pageData.pageNum}/${parent.totalPages} → ${pageTranslit.split(/\s+/).length} words`);
    }

    for (let start = 0; start < pageDocs.length; start += PAGE_BATCH) {
      const slice = pageDocs.slice(start, start + PAGE_BATCH);
      await Promise.all(slice.map(transliteratePage));
    }

    // Assemble doc-level output by joining per-page transliterations. The UI
    // can also render from page docs directly; transliteratedOutput exists
    // for download exports and admin / overview consumers.
    const finalPagesSnap = await parentRef.collection('pages').orderBy('pageNum').get();
    const assembledTranslit = finalPagesSnap.docs
      .map(d => d.data().transliteratedText ?? '')
      .filter(Boolean)
      .join('\n\n');
    const finalTranslit = rulesEnforcerAgent(assembledTranslit).text;

    await parentRef.update({
      transliteratedOutput: finalTranslit,
      status: 'done',
      completedAt: new Date().toISOString(),
    });
    pdfCache.delete(parentRef.id);
    console.log(`  ✓ transliteration complete — ${finalTranslit.split(/\s+/).length} words across ${pageDocs.length} pages`);
  } catch (err) {
    console.error(`[worker] Transliteration failed: ${err.message}`);
    await parentRef.update({
      status: 'failed',
      error: `Transliteration: ${err.message?.slice(0, 200)}`,
      completedAt: new Date().toISOString(),
    });
    pdfCache.delete(parentRef.id);
  }
}

async function processTranslationStage(parentDoc) {
  const parentRef = parentDoc.ref;
  const parent = parentDoc.data();
  console.log(`\n[worker] Translating ${parent.filename} (optional secondary stage)`);

  await parentRef.update({ translationStatus: 'running' });
  try {
    // Run the canonical translator → enforcer → smoother → enforcer chain over
    // the assembled Gujarati, chunked. Mirrors the existing /jobs/ pipeline.
    const chunks = deterministicChunk(parent.gujaratiOutput ?? '');
    if (chunks.length === 0) throw new Error('No Gujarati content to translate');
    console.log(`  Chunked into ${chunks.length} piece${chunks.length === 1 ? '' : 's'}`);

    const translations = new Array(chunks.length).fill('');
    const smoothed = new Array(chunks.length).fill('');

    for (let start = 0; start < chunks.length; start += BATCH) {
      const slice = chunks.slice(start, start + BATCH);
      await Promise.all(slice.map(async (chunk, k) => {
        const i = start + k;
        // Translate
        const tOut = await translatorAgent(chunk, i, chunks.length);
        translations[i] = rulesEnforcerAgent(tOut.translation).text;
        console.log(`    ✓ translated chunk ${i + 1}/${chunks.length}`);
        // Smooth
        try {
          const sOut = await smootherAgent(translations[i]);
          smoothed[i] = rulesEnforcerAgent(sOut.smoothed).text;
        } catch (err) {
          console.warn(`    ⚠ smoother fallback on chunk ${i + 1}: ${err.message}`);
          smoothed[i] = translations[i];
        }
        console.log(`    ✓ smoothed chunk ${i + 1}/${chunks.length}`);
      }));
    }

    const assembledEn = assemblerAgent(smoothed);
    const finalEn = rulesEnforcerAgent(assembledEn).text;

    await parentRef.update({
      translationOutput: finalEn,
      translationStatus: 'done',
    });
    console.log(`  ✓ translation complete — ${finalEn.split(/\s+/).length} words across ${chunks.length} chunks`);
  } catch (err) {
    console.error(`[worker] Translation failed: ${err.message}`);
    await parentRef.update({
      translationStatus: 'failed',
      translationError: err.message?.slice(0, 200) ?? 'Unknown',
    });
  }
}

