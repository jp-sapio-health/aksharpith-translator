// ── Claude Agent SDK ─────────────────────────────────────────────────────────
// Auth is via CLAUDE_CODE_OAUTH_TOKEN env var (loaded from .env.local at top of
// this file). Generated by `claude setup-token` — 1-year lifetime.
//
// Why SDK and not the raw `claude` CLI?
//   The CLI is the agentic IDE shell. Even with `-p`, it loads hooks/LSP/MCP/
//   plugins/CLAUDE.md auto-discovery and runs the agent loop. Under non-trivial
//   prompts it opens 19+ TCP connections and hangs at the 5-min Node timeout.
//   The SDK calls Anthropic directly — clean HTTP, no agent overhead.
//
// We disable all built-in tools and cap maxTurns at 1 so query() acts as a
// pure system+user → text completion — no Read/Edit/Bash/Grep, no agent loop.

import { query } from '@anthropic-ai/claude-agent-sdk';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';

if (!process.env.CLAUDE_CODE_OAUTH_TOKEN) {
  console.error('Missing CLAUDE_CODE_OAUTH_TOKEN. Run `claude setup-token` and add to .env.local.');
  process.exit(1);
}

// Isolated cwd keeps the SDK from auto-discovering workspace CLAUDE.md / .claude/.
const SDK_CWD = mkdtempSync(`${tmpdir()}/aksharpith-sdk-`);

async function callClaudeOnce(params) {
  const userPrompt = params.messages.map(m => typeof m.content === 'string' ? m.content : '').join('\n');

  const q = query({
    prompt: userPrompt,
    options: {
      systemPrompt: params.system,
      model: params.model,
      tools: [],                       // pure text completion — no Read/Edit/Bash/etc.
      maxTurns: 1,                     // single response, no agent loop
      cwd: SDK_CWD,
      permissionMode: 'bypassPermissions',
    },
  });

  let text = '';
  let errorKind = null;
  for await (const msg of q) {
    if (msg.type === 'assistant') {
      if (msg.error) errorKind = msg.error;
      for (const block of msg.message.content ?? []) {
        if (block.type === 'text' && typeof block.text === 'string') text += block.text;
      }
    } else if (msg.type === 'result' && msg.subtype !== 'success') {
      errorKind = errorKind ?? msg.subtype;
    }
  }

  if (errorKind) throw new Error(`Claude SDK error: ${errorKind}`);
  if (!text.trim()) throw new Error('Empty response from Claude SDK');
  return text;
}

async function callClaude(params) {
  let lastErr;
  for (let attempt = 0; attempt <= SDK_MAX_RETRIES; attempt++) {
    try {
      return await callClaudeOnce(params);
    } catch (err) {
      lastErr = err;
      console.error(`  [callClaude] attempt ${attempt + 1}/${SDK_MAX_RETRIES + 1} failed: ${err.message}`);
      if (attempt < SDK_MAX_RETRIES) {
        await new Promise(r => setTimeout(r, SDK_RETRY_DELAY_MS * (attempt + 1)));
      }
    }
  }
  throw lastErr;
}

// ── Chunker ──────────────────────────────────────────────────────────────────

function isVerseBlock(para) {
  const lines = para.split('\n').map(l => l.trim()).filter(Boolean);
  if (lines.length < 2) return false;
  const quotedVerse = lines.some(l => /^[\u201c\u201d"'\u2018\u2019]/.test(l) && /[āīūṛṅñṭḍṇśṣḥ]/.test(l));
  const avgLen = lines.reduce((s, l) => s + l.length, 0) / lines.length;
  const similarLength = lines.length >= 2 && lines.every(l => Math.abs(l.length - avgLen) < avgLen * 0.5);
  const diacriticLines = lines.filter(l => /[āīūṛṅñṭḍṇśṣḥ]/.test(l)).length;
  const mostlyDiacritic = diacriticLines >= lines.length * 0.5;
  return quotedVerse || (similarLength && mostlyDiacritic);
}

function deterministicChunk(text) {
  const trimmed = text.trim();
  if (!trimmed) return [];
  const totalWords = trimmed.split(/\s+/).filter(Boolean).length;
  if (totalWords <= 500) return [trimmed];

  let rawParagraphs = trimmed.split(/\n\s*\n/);
  const hasGiantPara = rawParagraphs.some(p => p.trim().split(/\s+/).length > 500);
  if (hasGiantPara) rawParagraphs = trimmed.split(/\n/).filter(l => l.trim());

  const groups = [];
  let pendingVerse = null;
  for (const para of rawParagraphs) {
    const p = para.trim();
    if (!p) continue;
    if (isVerseBlock(p)) {
      if (groups.length > 0) groups[groups.length - 1] += '\n\n' + p;
      else pendingVerse = pendingVerse ? pendingVerse + '\n\n' + p : p;
    } else {
      if (pendingVerse) { groups.push(pendingVerse + '\n\n' + p); pendingVerse = null; }
      else groups.push(p);
    }
  }
  if (pendingVerse) groups.push(pendingVerse);

  const chunks = [];
  let current = [], currentWords = 0;
  for (const group of groups) {
    const groupWords = group.split(/\s+/).length;
    if (currentWords + groupWords > 500 && currentWords >= 300) {
      chunks.push(current.join('\n\n'));
      current = [group]; currentWords = groupWords;
    } else {
      current.push(group); currentWords += groupWords;
    }
  }
  if (current.length > 0) {
    if (currentWords < 150 && chunks.length > 0) chunks[chunks.length - 1] += '\n\n' + current.join('\n\n');
    else chunks.push(current.join('\n\n'));
  }
  return chunks.length > 0 ? chunks : [trimmed];
}

// ── XML output parsers (mirrors lib/parser.ts) ───────────────────────────────

function stripFences(raw) {
  let s = raw.trim();
  const m = s.match(/^```(?:[a-zA-Z]+)?\s*\n([\s\S]*?)\n\s*```\s*$/);
  if (m) s = m[1].trim();
  return s;
}

function extractSingleTag(source, tag, stage) {
  const open = `<${tag}>`;
  const close = `</${tag}>`;
  const firstOpen = source.indexOf(open);
  if (firstOpen === -1) throw new Error(`[${stage}] Missing <${tag}> opening tag`);
  const lastOpen = source.lastIndexOf(open);
  if (lastOpen !== firstOpen) throw new Error(`[${stage}] Multiple <${tag}> opening tags`);
  const closeIdx = source.indexOf(close, firstOpen + open.length);
  if (closeIdx === -1) throw new Error(`[${stage}] Missing </${tag}> closing tag`);
  const lastClose = source.lastIndexOf(close);
  if (lastClose !== closeIdx) throw new Error(`[${stage}] Multiple </${tag}> closing tags`);
  return source.slice(firstOpen + open.length, closeIdx).trim();
}

function parseTranslatorXml(raw) {
  if (typeof raw !== 'string') throw new Error('[translator] Empty or non-string output');
  const cleaned = stripFences(raw);
  if (!cleaned) throw new Error('[translator] Empty output');
  const translation = extractSingleTag(cleaned, 'translation', 'translator');
  if (!translation) throw new Error('[translator] Empty <translation> block');
  const flagsBlock = extractSingleTag(cleaned, 'flags', 'translator');
  const flags = [];
  const re = /<flag>([\s\S]*?)<\/flag>/g;
  let m;
  while ((m = re.exec(flagsBlock)) !== null) {
    const t = m[1].trim();
    if (t) flags.push(t);
  }
  return { translation, flags };
}

function parseSmootherXml(raw) {
  if (typeof raw !== 'string') throw new Error('[smoother] Empty or non-string output');
  const cleaned = stripFences(raw);
  if (!cleaned) throw new Error('[smoother] Empty output');
  const smoothed = extractSingleTag(cleaned, 'smoothed', 'smoother');
  if (!smoothed) throw new Error('[smoother] Empty <smoothed> block');
  return { smoothed };
}

// ── Agent functions ──────────────────────────────────────────────────────────

async function translatorAgent(chunk, chunkIndex, totalChunks) {
  const raw = await callClaude({
    model: SONNET, max_tokens: 8192,
    system: TRANSLATOR_SYSTEM,
    messages: [{ role: 'user', content: `Chunk ${chunkIndex + 1} of ${totalChunks}. Translate the following Gujarati text into English following the rules above. For verse or poetic lines, include the Roman transliteration in curly quotes first, then the English meaning in parentheses — both mandatory. Output ONLY the two XML blocks specified in the system prompt: <translation>…</translation><flags>…</flags>.\n\nGUJARATI:\n${chunk}` }],
  });
  return parseTranslatorXml(raw);
}

async function smootherAgent(text) {
  const raw = await callClaude({
    model: SONNET, max_tokens: 8192,
    system: SMOOTHER_SYSTEM,
    messages: [{ role: 'user', content: `Smooth the following passage per the rules above. Output ONLY <smoothed>…</smoothed>.\n\n${text}` }],
  });
  return parseSmootherXml(raw);
}

// Defensive: if the smoother stripped macrons (ā) from verse transliterations,
// restore the original line from the translator output. Mirrors the
// preserveMacrons helper in lib/pipeline.ts.
function preserveMacrons(translatorText, smootherText) {
  const MACRON = /[Āā]/g;
  const stripMacron = (s) => s.replace(/Ā/g, 'A').replace(/ā/g, 'a');
  const tCount = (translatorText.match(MACRON) ?? []).length;
  const sCount = (smootherText.match(MACRON) ?? []).length;
  if (tCount === 0 || sCount >= tCount) return { text: smootherText, restored: 0 };
  const verseLines = translatorText.split('\n').filter(l => /[Āā]/.test(l));
  let patched = smootherText;
  let restored = 0;
  for (const verseLine of verseLines) {
    if (patched.includes(verseLine)) continue;
    const stripped = stripMacron(verseLine);
    if (patched.includes(stripped)) {
      patched = patched.replace(stripped, verseLine);
      restored += (verseLine.match(MACRON) ?? []).length;
    }
  }
  return { text: patched, restored };
}

function assemblerAgent(smoothedChunks) {
  if (smoothedChunks.length <= 1) return smoothedChunks[0] ?? '';
  const result = [];
  for (let i = 0; i < smoothedChunks.length; i++) {
    const chunk = smoothedChunks[i].trim();
    if (!chunk) continue;
    if (result.length > 0) {
      const prevSentences = result[result.length - 1].split(/(?<=[.!?])\s+/).filter(Boolean);
      const currSentences = chunk.split(/(?<=[.!?])\s+/).filter(Boolean);
      let overlap = 0;
      for (let n = Math.min(2, prevSentences.length, currSentences.length); n >= 1; n--) {
        if (prevSentences.slice(-n).join(' ').trim() === currSentences.slice(0, n).join(' ').trim()) { overlap = n; break; }
      }
      result.push(overlap > 0 ? currSentences.slice(overlap).join(' ') : chunk);
    } else {
      result.push(chunk);
    }
  }
  return result.join('\n\n');
}

// ── Rules enforcer (simplified — full rules loaded via tsx above) ─────────────
// The full rulesEnforcerAgent is in pipeline.ts. We load it via tsx if possible.

let rulesEnforcerAgent;
try {
  const { execSync } = await import('node:child_process');
  // Export the function as a serialized module isn't practical,
  // so we apply basic rules inline. The full enforcer runs regex replacements.
  // For the worker, we'll do a simpler version that covers the essentials.
  rulesEnforcerAgent = (text) => {
    let t = text;
    // Curly quotes
    let openDouble = true;
    t = t.replace(/"/g, () => { const q = openDouble ? '\u201c' : '\u201d'; openDouble = !openDouble; return q; });
    t = t.replace(/'([^']{2,})'/g, '\u2018$1\u2019');
    // Em dash → spaced en dash
    t = t.replace(/\u2014/g, ' \u2013 ').replace(/ {2,}\u2013 {2,}/g, ' \u2013 ');
    // Clean up double spaces
    t = t.replace(/ {2,}/g, ' ').replace(/^ +/gm, '');
    return { text: t, corrections: [], totalFixes: 0 };
  };
} catch {
  rulesEnforcerAgent = (text) => ({ text, corrections: [], totalFixes: 0 });
}

